CREATE DATABASE saryarka_travel;
-- psql ішінде:  \c saryarka_travel

-- Қайта іске қосу кезінде ескі кестелерді тазалау (тәуелділіктің кері реті)
DROP TABLE IF EXISTS reviews            CASCADE;
DROP TABLE IF EXISTS insurance          CASCADE;
DROP TABLE IF EXISTS payments           CASCADE;
DROP TABLE IF EXISTS booking_participants CASCADE;
DROP TABLE IF EXISTS bookings           CASCADE;
DROP TABLE IF EXISTS discounts          CASCADE;
DROP TABLE IF EXISTS clients            CASCADE;
DROP TABLE IF EXISTS tour_guides        CASCADE;
DROP TABLE IF EXISTS tours              CASCADE;
DROP TABLE IF EXISTS flights            CASCADE;
DROP TABLE IF EXISTS guides             CASCADE;
DROP TABLE IF EXISTS transport          CASCADE;
DROP TABLE IF EXISTS package_hotels     CASCADE;
DROP TABLE IF EXISTS tour_packages      CASCADE;
DROP TABLE IF EXISTS hotels             CASCADE;
DROP TABLE IF EXISTS destinations       CASCADE;
DROP TABLE IF EXISTS airlines           CASCADE;
DROP TABLE IF EXISTS countries          CASCADE;

-- ---------------------------------------------------------------------
-- 1. Анықтамалықтар
-- ---------------------------------------------------------------------

-- Елдер. entry_regime Қазақстан азаматтары үшін кіру режимін көрсетеді.
CREATE TABLE countries (
    country_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_name        VARCHAR(60)  NOT NULL UNIQUE,
    iso_code            CHAR(2)      NOT NULL UNIQUE,
    continent           VARCHAR(20)  NOT NULL
                        CHECK (continent IN ('Asia', 'Europe', 'Africa')),
    currency_code       CHAR(3)      NOT NULL,
    entry_regime        VARCHAR(20)  NOT NULL
                        CHECK (entry_regime IN ('domestic', 'visa_free', 'visa_on_arrival', 'visa_required')),
    insurance_mandatory BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Авиакомпаниялар
CREATE TABLE airlines (
    airline_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airline_name  VARCHAR(60) NOT NULL UNIQUE,
    iata_code     CHAR(2)     NOT NULL UNIQUE,
    country_id    INTEGER     NOT NULL REFERENCES countries (country_id),
    is_low_cost   BOOLEAN     NOT NULL DEFAULT FALSE,
    is_active     BOOLEAN     NOT NULL DEFAULT TRUE
);

-- Бағыттар (қалалар мен курорттар), оның ішінде Қазақстандағы ұшу хабтары
CREATE TABLE destinations (
    destination_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id        INTEGER      NOT NULL REFERENCES countries (country_id),
    destination_name  VARCHAR(80)  NOT NULL,
    destination_type  VARCHAR(20)  NOT NULL
                      CHECK (destination_type IN ('beach_resort', 'city', 'island', 'mountain', 'cultural_site')),
    airport_code      CHAR(3)      UNIQUE,
    utc_offset        NUMERIC(3,1) NOT NULL CHECK (utc_offset BETWEEN -12 AND 14),
    best_season       VARCHAR(10)  NOT NULL
                      CHECK (best_season IN ('winter', 'spring', 'summer', 'autumn', 'all_year')),
    is_departure_hub  BOOLEAN      NOT NULL DEFAULT FALSE,
    description       VARCHAR(255),
    CONSTRAINT uq_destination_country_name UNIQUE (country_id, destination_name)
);

-- Қонақүйлер (бір түнге нетто тариф, екі кісілік номер үшін)
CREATE TABLE hotels (
    hotel_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id         INTEGER       NOT NULL REFERENCES destinations (destination_id),
    hotel_name             VARCHAR(100)  NOT NULL UNIQUE,
    star_rating            SMALLINT      NOT NULL CHECK (star_rating BETWEEN 1 AND 5),
    board_type             VARCHAR(3)    NOT NULL DEFAULT 'BB'
                           CHECK (board_type IN ('RO', 'BB', 'HB', 'FB', 'AI', 'UAI')),
    price_per_night        NUMERIC(10,2) NOT NULL CHECK (price_per_night > 0),
    rooms_total            SMALLINT      NOT NULL CHECK (rooms_total > 0),
    distance_to_center_km  NUMERIC(4,1)  CHECK (distance_to_center_km >= 0),
    contact_email          VARCHAR(100),
    is_active              BOOLEAN       NOT NULL DEFAULT TRUE
);

-- Турпакеттер (өнім шаблоны)
CREATE TABLE tour_packages (
    package_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_name      VARCHAR(120)  NOT NULL UNIQUE,
    destination_id    INTEGER       NOT NULL REFERENCES destinations (destination_id),
    tour_type         VARCHAR(20)   NOT NULL
                      CHECK (tour_type IN ('beach', 'cultural', 'city_break', 'adventure', 'wellness', 'ski')),
    duration_days     SMALLINT      NOT NULL CHECK (duration_days BETWEEN 2 AND 30),
    base_price        NUMERIC(12,2) NOT NULL CHECK (base_price > 0),
    min_group_size    SMALLINT      NOT NULL DEFAULT 2 CHECK (min_group_size > 0),
    max_group_size    SMALLINT      NOT NULL CHECK (max_group_size >= 2),
    visa_support      BOOLEAN       NOT NULL DEFAULT FALSE,
    description       VARCHAR(255),
    is_active         BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_package_group CHECK (max_group_size >= min_group_size)
);

-- M:M байланыс: турпакет <-> қонақүй
CREATE TABLE package_hotels (
    package_id     INTEGER     NOT NULL REFERENCES tour_packages (package_id) ON DELETE CASCADE,
    hotel_id       INTEGER     NOT NULL REFERENCES hotels (hotel_id),
    nights         SMALLINT    NOT NULL CHECK (nights > 0),
    stay_order     SMALLINT    NOT NULL DEFAULT 1 CHECK (stay_order > 0),
    room_category  VARCHAR(20) NOT NULL DEFAULT 'standard'
                   CHECK (room_category IN ('standard', 'superior', 'deluxe', 'family', 'suite')),
    PRIMARY KEY (package_id, hotel_id)
);

-- Жергілікті көлік (трансфер, автобус, микроавтобус)
CREATE TABLE transport (
    transport_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id        INTEGER       NOT NULL REFERENCES countries (country_id),
    transport_type    VARCHAR(15)   NOT NULL
                      CHECK (transport_type IN ('bus', 'minibus', 'van', 'car', 'train', 'boat')),
    provider_name     VARCHAR(100)  NOT NULL,
    vehicle_model     VARCHAR(60),
    capacity          SMALLINT      NOT NULL CHECK (capacity > 0),
    daily_rate        NUMERIC(10,2) NOT NULL CHECK (daily_rate > 0),
    has_air_conditioning BOOLEAN    NOT NULL DEFAULT TRUE,
    plate_number      VARCHAR(20)   UNIQUE,
    is_active         BOOLEAN       NOT NULL DEFAULT TRUE
);

-- Гидтер мен топ жетекшілері
CREATE TABLE guides (
    guide_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name           VARCHAR(100)  NOT NULL,
    country_id          INTEGER       NOT NULL REFERENCES countries (country_id),
    primary_language    VARCHAR(20)   NOT NULL,
    secondary_language  VARCHAR(20),
    phone               VARCHAR(20),
    email               VARCHAR(100)  UNIQUE,
    license_number      VARCHAR(20)   NOT NULL UNIQUE,
    experience_years    SMALLINT      NOT NULL DEFAULT 0 CHECK (experience_years BETWEEN 0 AND 50),
    daily_fee           NUMERIC(10,2) NOT NULL CHECK (daily_fee > 0),
    specialization      VARCHAR(15)   NOT NULL
                        CHECK (specialization IN ('escort', 'cultural', 'adventure', 'beach', 'city')),
    hire_date           DATE          NOT NULL,
    is_active           BOOLEAN       NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- 2. Ұшу және тур департурлары
-- ---------------------------------------------------------------------

-- Рейстер (жергілікті әуежай уақытымен)
CREATE TABLE flights (
    flight_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number          VARCHAR(8)    NOT NULL,
    airline_id             INTEGER       NOT NULL REFERENCES airlines (airline_id),
    origin_destination_id  INTEGER       NOT NULL REFERENCES destinations (destination_id),
    arrival_destination_id INTEGER       NOT NULL REFERENCES destinations (destination_id),
    departure_at           TIMESTAMP     NOT NULL,
    arrival_at             TIMESTAMP     NOT NULL,
    cabin_class            VARCHAR(10)   NOT NULL DEFAULT 'economy'
                           CHECK (cabin_class IN ('economy', 'premium', 'business')),
    seat_price             NUMERIC(10,2) NOT NULL CHECK (seat_price > 0),
    seats_blocked          SMALLINT      NOT NULL CHECK (seats_blocked > 0),
    flight_status          VARCHAR(10)   NOT NULL DEFAULT 'scheduled'
                           CHECK (flight_status IN ('scheduled', 'completed', 'cancelled')),
    delay_minutes          SMALLINT      NOT NULL DEFAULT 0 CHECK (delay_minutes >= 0),
    CONSTRAINT uq_flight_number_departure UNIQUE (flight_number, departure_at)
);

-- Тур департурлары: нақты күнге жоспарланған тур
CREATE TABLE tours (
    tour_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id            INTEGER       NOT NULL REFERENCES tour_packages (package_id),
    transport_id          INTEGER       NOT NULL REFERENCES transport (transport_id),
    outbound_flight_id    INTEGER       NOT NULL UNIQUE REFERENCES flights (flight_id),
    return_flight_id      INTEGER       NOT NULL UNIQUE REFERENCES flights (flight_id),
    departure_date        DATE          NOT NULL,
    return_date           DATE          NOT NULL,
    price_per_person      NUMERIC(12,2) NOT NULL CHECK (price_per_person > 0),
    net_cost_per_person   NUMERIC(12,2) NOT NULL CHECK (net_cost_per_person >= 0),
    max_participants      SMALLINT      NOT NULL CHECK (max_participants > 0),
    tour_status           VARCHAR(10)   NOT NULL DEFAULT 'scheduled'
                          CHECK (tour_status IN ('scheduled', 'confirmed', 'completed', 'cancelled')),
    CONSTRAINT chk_tour_dates CHECK (return_date > departure_date),
    CONSTRAINT uq_tour_package_date UNIQUE (package_id, departure_date)
);

-- M:M байланыс: тур <-> гид
CREATE TABLE tour_guides (
    tour_id          INTEGER       NOT NULL REFERENCES tours (tour_id) ON DELETE CASCADE,
    guide_id         INTEGER       NOT NULL REFERENCES guides (guide_id),
    assignment_role  VARCHAR(15)   NOT NULL DEFAULT 'lead'
                     CHECK (assignment_role IN ('lead', 'assistant', 'local_expert')),
    assigned_on      DATE          NOT NULL,
    agreed_fee       NUMERIC(10,2) NOT NULL CHECK (agreed_fee > 0),
    PRIMARY KEY (tour_id, guide_id)
);

-- ---------------------------------------------------------------------
-- 3. Клиенттер және коммерциялық транзакциялар
-- ---------------------------------------------------------------------

-- Клиенттер (ересектер мен балалар; бала жолаушылар да осы кестеде)
CREATE TABLE clients (
    client_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name         VARCHAR(40)  NOT NULL,
    last_name          VARCHAR(50)  NOT NULL,
    gender             CHAR(1)      NOT NULL CHECK (gender IN ('M', 'F')),
    birth_date         DATE         NOT NULL CHECK (birth_date >= DATE '1930-01-01'),
    email              VARCHAR(100) UNIQUE CHECK (email IS NULL OR email LIKE '%_@_%._%'),
    phone              VARCHAR(20),
    city               VARCHAR(40)  NOT NULL,
    passport_number    VARCHAR(12)  NOT NULL UNIQUE,
    passport_expiry    DATE         NOT NULL,
    registration_date  DATE         NOT NULL DEFAULT CURRENT_DATE,
    is_active          BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Жеңілдіктер мен промокодтар
CREATE TABLE discounts (
    discount_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discount_code     VARCHAR(20)   NOT NULL UNIQUE,
    discount_name     VARCHAR(80)   NOT NULL,
    discount_type     VARCHAR(10)   NOT NULL CHECK (discount_type IN ('percent', 'fixed')),
    discount_value    NUMERIC(10,2) NOT NULL CHECK (discount_value > 0),
    valid_from        DATE          NOT NULL,
    valid_to          DATE          NOT NULL,
    min_participants  SMALLINT      NOT NULL DEFAULT 1 CHECK (min_participants >= 1),
    max_uses          INTEGER       CHECK (max_uses > 0),
    is_active         BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_discount_period CHECK (valid_to >= valid_from),
    CONSTRAINT chk_discount_percent CHECK (discount_type <> 'percent' OR discount_value <= 50)
);

-- Брондаулар (клиент -> тур)
CREATE TABLE bookings (
    booking_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id            INTEGER      NOT NULL REFERENCES clients (client_id),
    tour_id              INTEGER      NOT NULL REFERENCES tours (tour_id),
    discount_id          INTEGER      REFERENCES discounts (discount_id),
    booking_date         DATE         NOT NULL,
    booking_status       VARCHAR(10)  NOT NULL DEFAULT 'pending'
                         CHECK (booking_status IN ('pending', 'confirmed', 'completed', 'cancelled')),
    booking_channel      VARCHAR(15)  NOT NULL DEFAULT 'office'
                         CHECK (booking_channel IN ('office', 'website', 'phone', 'instagram', 'partner')),
    cancellation_date    DATE,
    cancellation_reason  VARCHAR(30)
                         CHECK (cancellation_reason IN ('client_request', 'illness', 'visa_refused',
                                'tour_cancelled', 'schedule_conflict', 'payment_overdue')),
    special_requests     VARCHAR(200),
    CONSTRAINT chk_cancel_dates CHECK (cancellation_date IS NULL OR cancellation_date >= booking_date),
    CONSTRAINT chk_cancel_consistency CHECK (
        (booking_status = 'cancelled' AND cancellation_date IS NOT NULL AND cancellation_reason IS NOT NULL)
        OR (booking_status <> 'cancelled' AND cancellation_date IS NULL AND cancellation_reason IS NULL))
);

-- M:M байланыс: брондау <-> клиент (жолаушылар құрамы)
CREATE TABLE booking_participants (
    participant_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id       INTEGER       NOT NULL REFERENCES bookings (booking_id) ON DELETE CASCADE,
    client_id        INTEGER       NOT NULL REFERENCES clients (client_id),
    traveler_type    VARCHAR(10)   NOT NULL CHECK (traveler_type IN ('adult', 'child', 'infant')),
    unit_price       NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    visa_status      VARCHAR(15)   NOT NULL DEFAULT 'not_required'
                     CHECK (visa_status IN ('not_required', 'pending', 'approved', 'rejected')),
    room_type        VARCHAR(10)   NOT NULL DEFAULT 'double'
                     CHECK (room_type IN ('single', 'double', 'twin', 'family')),
    meal_preference  VARCHAR(12)   NOT NULL DEFAULT 'standard'
                     CHECK (meal_preference IN ('standard', 'vegetarian', 'halal', 'child_menu')),
    CONSTRAINT uq_participant UNIQUE (booking_id, client_id)
);

-- Төлемдер (қайтарымдар payment_type = 'refund' арқылы жазылады)
CREATE TABLE payments (
    payment_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id       INTEGER       NOT NULL REFERENCES bookings (booking_id),
    payment_date     DATE          NOT NULL,
    amount           NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    payment_method   VARCHAR(15)   NOT NULL
                     CHECK (payment_method IN ('card', 'mobile_banking', 'bank_transfer', 'cash', 'installment')),
    payment_type     VARCHAR(15)   NOT NULL
                     CHECK (payment_type IN ('deposit', 'installment', 'balance', 'full_payment', 'refund')),
    payment_status   VARCHAR(10)   NOT NULL DEFAULT 'completed'
                     CHECK (payment_status IN ('completed', 'pending', 'failed')),
    transaction_ref  VARCHAR(20)   NOT NULL UNIQUE,
    currency_code    CHAR(3)       NOT NULL DEFAULT 'KZT',
    note             VARCHAR(120)
);

-- Сақтандыру полистері (брондауға бір полис)
CREATE TABLE insurance (
    insurance_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id           INTEGER       NOT NULL UNIQUE REFERENCES bookings (booking_id) ON DELETE CASCADE,
    insurer_name         VARCHAR(60)   NOT NULL,
    plan_type            VARCHAR(10)   NOT NULL CHECK (plan_type IN ('basic', 'standard', 'premium')),
    coverage_amount_eur  NUMERIC(10,2) NOT NULL CHECK (coverage_amount_eur > 0),
    insured_persons      SMALLINT      NOT NULL CHECK (insured_persons > 0),
    premium_amount       NUMERIC(10,2) NOT NULL CHECK (premium_amount > 0),
    coverage_start       DATE          NOT NULL,
    coverage_end         DATE          NOT NULL,
    policy_number        VARCHAR(20)   NOT NULL UNIQUE,
    policy_status        VARCHAR(10)   NOT NULL DEFAULT 'active'
                         CHECK (policy_status IN ('active', 'expired', 'cancelled', 'claimed')),
    CONSTRAINT chk_insurance_period CHECK (coverage_end >= coverage_start)
);

-- Тур аяқталған соңғы пікірлер
CREATE TABLE reviews (
    review_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id           INTEGER      NOT NULL REFERENCES bookings (booking_id) ON DELETE CASCADE,
    client_id            INTEGER      NOT NULL REFERENCES clients (client_id),
    review_date          DATE         NOT NULL,
    overall_rating       SMALLINT     NOT NULL CHECK (overall_rating BETWEEN 1 AND 5),
    hotel_rating         SMALLINT     NOT NULL CHECK (hotel_rating BETWEEN 1 AND 5),
    guide_rating         SMALLINT     NOT NULL CHECK (guide_rating BETWEEN 1 AND 5),
    service_rating       SMALLINT     NOT NULL CHECK (service_rating BETWEEN 1 AND 5),
    would_recommend      BOOLEAN      NOT NULL,
    comment_text         VARCHAR(300),
    CONSTRAINT uq_review UNIQUE (booking_id, client_id)
);
